LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;

ENTITY abc IS
	PORT(LETRA: IN INTEGER RANGE 0 TO 100;
	       SEG: OUT STD_LOGIC_VECTOR(6 DOWNTO 0));
END abc;

ARCHITECTURE BEAS OF abc IS
BEGIN
	
	WITH LETRA SELECT
		SEG <= "1110111" WHEN 0, -- A
				 "0011111" WHEN 1, -- b
				 "1001111" WHEN 2, -- C
				 "0111101" WHEN 3, -- d
				 "1001111" WHEN 4, -- E
				 "1000111" WHEN 5, -- F
				 "1011111" WHEN 6, -- G
				 "0010111" WHEN 7, -- H
				 "0110000" WHEN 8, -- I
				 "0111100" WHEN 9, -- J
				 "1010111" WHEN 10, -- K
				 "0001110" WHEN 11, -- L
				 "1001001" WHEN 12, -- M
				 "1110110" WHEN 13, -- n
				 "1010101" WHEN 14, -- ñ
				 "0011101" WHEN 15, -- o
				 "1100111" WHEN 16, -- P
				 "1110011" WHEN 17, -- q
				 "0000101" WHEN 18, -- r
				 "1011011" WHEN 19, -- S
				 "0001111" WHEN 20, -- t
				 "0111110" WHEN 21, -- U
				 "0100011" WHEN 22, -- v
				 "1011100" WHEN 23, -- w
				 "0110111" WHEN 24, -- X
				 "0111011" WHEN 25, -- Y
				 "1101101" WHEN 26, -- Z
				 "0000000" WHEN OTHERS;			 
	
END BEAS;